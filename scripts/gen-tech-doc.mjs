#!/usr/bin/env node
/** Regenerates the data tables in docs/03-tech-tree.md (every tech) and
 *  docs/05-sites.md (home, deposits, site techs, map tiers) from src/data.
 *  Everything between the GENERATED markers is rewritten; the prose around
 *  it is hand-written. Run after any tech, site or balance change:
 *    node scripts/gen-tech-doc.mjs          (write)
 *    node scripts/gen-tech-doc.mjs --check  (exit 1 if a doc is stale) */
import { build } from 'esbuild';
import { readFileSync, writeFileSync, mkdtempSync, rmSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join, dirname } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const DOCS = [
  { file: join(root, 'docs/03-tech-tree.md'), render: renderTechs },
  { file: join(root, 'docs/05-sites.md'), render: renderSites },
];
const BEGIN = '<!-- BEGIN GENERATED: node scripts/gen-tech-doc.mjs -->';
const END = '<!-- END GENERATED -->';

const tmp = mkdtempSync(join(tmpdir(), 'techdoc-'));
const out = join(tmp, 'techs.mjs');
try {
  await build({
    stdin: {
      contents: `
        export { TECHS, TECH_ORDER, ERA_NAMES, LANES, DOCTRINES, ERA_GATES, describeTech } from './src/data/techs';
        export { ERA_COST_SCALE, CHARTER_TECHS, QUEUE_MAX } from './src/data/balance';
        export { INSIGHTS } from './src/data/insights';
        export { SITES } from './src/data/sites';
        export { RESOURCES } from './src/data/resources';
        export { PROSPECTS, PROSPECT_IDS } from './src/data/lunarMap';
        export { DEPOSIT_PLAN, DEPOSIT_INFO } from './src/data/deposits';
        export { SURVEY_TIERS } from './src/data/balance';
        export { SITE_ORDER } from './src/data/sites';`,
      resolveDir: root, loader: 'ts',
    },
    bundle: true, format: 'esm', platform: 'node', outfile: out, logLevel: 'error',
  });
  const T = await import(pathToFileURL(out).href);
  let stale = false;
  for (const { file, render } of DOCS) {
    const doc = readFileSync(file, 'utf8');
    const a = doc.indexOf(BEGIN), b = doc.indexOf(END);
    if (a < 0 || b < a) throw new Error(`${file}: GENERATED markers missing`);
    const next = doc.slice(0, a + BEGIN.length) + '\n' + render(T) + doc.slice(b);
    const rel = file.slice(root.length + 1);
    if (process.argv.includes('--check')) {
      if (next !== doc) { console.error(`${rel} is stale: run node scripts/gen-tech-doc.mjs`); stale = true; }
      else console.log(`${rel} is current`);
    } else {
      writeFileSync(file, next);
      console.log(`wrote ${rel}`);
    }
  }
  if (stale) process.exitCode = 1;
} finally {
  rmSync(tmp, { recursive: true, force: true });
}

function renderTechs(T) {
  const { TECHS, TECH_ORDER, ERA_NAMES, LANES, DOCTRINES, ERA_GATES, ERA_COST_SCALE, INSIGHTS, SITES, RESOURCES, PROSPECTS, describeTech } = T;
  const esc = (s) => String(s).replace(/\|/g, '\\|');
  const glyph = (r) => RESOURCES[r]?.glyph ?? r;
  const laneOf = Object.fromEntries(LANES.map((l) => [l.id, l.glyph]));
  const name = (id) => TECHS[id]?.name ?? id;
  const insightOf = Object.fromEntries(INSIGHTS.map((i) => [i.tech, i]));
  const doctrineOf = (id) => Object.values(DOCTRINES).find((d) => d.members.includes(id));
  const cost = (def, era) => Math.round(def.costData * ERA_COST_SCALE[era]);
  const lines = [];
  const L = (s = '') => lines.push(s);

  L('Costs are data after `ERA_COST_SCALE`; `robotic →` marks the resolved era and cost on robotic');
  L('runs. Pros and cons are generated by `describeTech()` exactly as the tree cards show them');
  L('(no site filter, human crew). ✎ = an insight discount can be earned in-base; ◈ = doctrine pick.');
  L();
  for (let era = 1; era <= 8; era++) {
    const ids = TECH_ORDER.filter((id) => TECHS[id].era === era);
    const moved = TECH_ORDER.filter((id) => TECHS[id].robotic?.era === era && TECHS[id].era !== era);
    L(`### Era ${era} · ${ERA_NAMES[era]}`);
    L();
    const g = ERA_GATES[era];
    if (g) {
      L(`Opens with ${T.CHARTER_TECHS} techs of era ${era - 1}, or 1 plus the deed: **${g.deed}**` +
        (g.roboticRequires ? ` (robotic runs also need ${name(g.roboticRequires)})` : '') + '.');
      L();
    }
    L('| Tech | Lane | Data | Goods | Requires | Pros | Cons |');
    L('|---|---|---|---|---|---|---|');
    for (const id of ids) {
      const d = TECHS[id];
      const tags = [];
      const doc = doctrineOf(id);
      if (doc) tags.push(`◈ ${esc(doc.question)}`);
      if (d.breakthrough) {
        const hosts = d.breakthrough.hosts.map((h) => PROSPECTS[h]?.short ?? PROSPECTS[h]?.name ?? h).join(', ');
        tags.push(`✦ breakthrough — survey ${esc(hosts)}`);
      }
      if (d.sites) tags.push(`sites: ${d.sites.map((s) => SITES[s].name).join(', ')}`);
      if (d.expeditions) tags.push(`${d.expeditions.join('/')} only`);
      if (d.crewTech) tags.push('crew tech (robotic: after Cohabitation)');
      const ins = insightOf[id];
      const nm = `**${esc(d.name)}**${tags.length ? `<br><sub>${tags.join(' · ')}</sub>` : ''}`;
      let data = String(cost(d, era));
      if (d.robotic) {
        const re = d.robotic.era ?? era;
        const rc = Math.round((d.robotic.costData ?? d.costData) * ERA_COST_SCALE[re]);
        data += `<br><sub>robotic → ${re !== era ? `E${re} · ` : ''}${rc}</sub>`;
      }
      if (ins) data += `<br><sub>✎ −${Math.round(ins.discount * 100)}%: ${esc(ins.hint)}</sub>`;
      const goods = Object.entries(d.costGoods ?? {}).map(([r, v]) => `${v}${glyph(r)}`).join(' ') || '—';
      const req = [
        ...d.requires.map(name),
        ...(d.requiresAny?.length ? [`any of ${d.requiresAny.map(name).join(' / ')}`] : []),
      ].join(', ') || '—';
      const fx = describeTech(d, {});
      const pros = fx.filter((l) => l.sign === 'pro').map((l) => esc(l.text)).join('<br>') || '—';
      const cons = fx.filter((l) => l.sign === 'con').map((l) => esc(l.text)).join('<br>') || '—';
      L(`| ${nm} | ${d.lane ? laneOf[d.lane] : '★'} | ${data} | ${goods} | ${esc(req)} | ${pros} | ${cons} |`);
    }
    if (moved.length) {
      L();
      L(`On robotic runs ${moved.map(name).join(', ')} also ${moved.length > 1 ? 'resolve' : 'resolves'} into this era.`);
    }
    L();
  }
  L('### Doctrines');
  L();
  L('| Era | Question | Members | Site notes |');
  L('|---|---|---|---|');
  for (const d of Object.values(DOCTRINES)) {
    const notes = Object.entries(d.siteNote).map(([s, n]) => `${SITES[s].name}: ${esc(n)}`).join('<br>') || '—';
    L(`| ${d.era} | ${esc(d.question)} | ${d.members.map(name).join(' / ')} | ${notes} |`);
  }
  L();
  const total = TECH_ORDER.length;
  const bts = TECH_ORDER.filter((id) => TECHS[id].breakthrough).length;
  L(`${total} techs: ${total - bts} researchable from the start of their era, ${bts} breakthroughs,`);
  L(`${Object.keys(DOCTRINES).length} doctrines, ${INSIGHTS.length} insights.`);
  L();
  return lines.join('\n');
}

function renderSites(T) {
  const { TECHS, TECH_ORDER, SITES, SITE_ORDER, DEPOSIT_PLAN, DEPOSIT_INFO, DOCTRINES, PROSPECTS, PROSPECT_IDS, SURVEY_TIERS } = T;
  const esc = (s) => String(s).replace(/\|/g, '\\|');
  const lines = [];
  const L = (s = '') => lines.push(s);
  const ll = ({ lat, lon }) => `${Math.abs(lat)}°${lat < 0 ? 'S' : 'N'} ${Math.abs(lon)}°${lon < 0 ? 'W' : 'E'}`;
  const tierTech = (t) => TECH_ORDER.find((id) => TECHS[id].effects.some((fx) => fx.kind === 'survey' && fx.tier === t));

  L('### Survey tiers (the map grows with research)');
  L();
  L('| Tier | Coverage | Local reveal | Outpost slots | Unlocked by |');
  L('|---|---|---|---|---|');
  const cover = ['the landing site', 'regional prospects (≤27°)', 'the whole near side', 'the far side', 'buried prospects'];
  SURVEY_TIERS.forEach((t, i) => {
    const tid = tierTech(i);
    L(`| T${i} ${t.label} | ${cover[i] ?? '—'} | ${i >= 2 ? 'whole map' : `${t.revealM} m`} | ${t.slots} | ${tid ? TECHS[tid].name : 'landing'} |`);
  });
  L();
  for (const sid of SITE_ORDER) {
    const s = SITES[sid];
    L(`### ${s.name}`);
    L();
    L(`Home ${ll(s.home)}`);
    L();
    L('| Deposit | Count | Radius | Distance from Lander | Effect when built on |');
    L('|---|---|---|---|---|');
    for (const d of DEPOSIT_PLAN[sid]) {
      const info = DEPOSIT_INFO[d.kind];
      const g = d.guaranteed ? ` (${d.guaranteed.count} within ${d.guaranteed.minM}–${d.guaranteed.maxM} m)` : '';
      L(`| ${info.glyph} ${info.name} | ${d.count}${g} | ${d.rMin === d.rMax ? d.rMin : `${d.rMin}–${d.rMax}`} m | ${d.dMin}–${d.dMax} m | ${esc(info.ghost)} |`);
    }
    L();
    const only = TECH_ORDER.filter((id) => TECHS[id].sites?.includes(sid) && !TECHS[id].breakthrough);
    const absent = TECH_ORDER.filter((id) => TECHS[id].sites && !TECHS[id].sites.includes(sid) && !TECHS[id].breakthrough);
    if (only.length) L(`**Site techs:** ${only.map((id) => TECHS[id].name).join(', ')}.`);
    if (absent.length) L(`**Not here:** ${absent.map((id) => TECHS[id].name).join(', ')}.`);
    const notes = Object.values(DOCTRINES).filter((d) => d.siteNote[sid]).map((d) => `${esc(d.question)} ${esc(d.siteNote[sid])}`);
    if (notes.length) L(`**Doctrine answers:** ${notes.join(' ')}`);
    const bts = TECH_ORDER.filter((id) => TECHS[id].breakthrough);
    const hosts = bts.map((id) => {
      const hs = TECHS[id].breakthrough.hosts.map((h) => PROSPECTS[h]).filter(Boolean);
      return `${TECHS[id].name} (${hs.map((p) => p.short ?? p.name).join(', ')})`;
    });
    if (hosts.length && sid === SITE_ORDER[SITE_ORDER.length - 1]) {
      L();
      L(`**Breakthrough hosts (every site):** ${hosts.join('; ')}. ${PROSPECT_IDS.length} prospects in all.`);
    }
    L();
  }
  return lines.join('\n');
}
